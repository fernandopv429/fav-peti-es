import { preencherDocxTemplate } from '../src/features/entrevista/lib/preencherDocxTemplate.js';
import { montarDadosTemplate } from '../src/features/entrevista/lib/dadosTemplate.js';
import { mapearCasoDeWebhook } from '../base44/shared/mapearWebhook.js';
import { calcularVerbasCaso } from '../base44/shared/mathUtils.js';
import fs from 'node:fs';
const [,, evJson, casoJson, url, out] = process.argv;
const ev = JSON.parse(fs.readFileSync(evJson, 'utf8'));
const aj = JSON.parse(fs.readFileSync(casoJson, 'utf8')).analise_json;
const novo = mapearCasoDeWebhook(ev.payload.data);
const caso = { ...aj.caso, data_admissao: novo.data_admissao, jornada_freq_extra: novo.jornada_freq_extra, prorrogacao_jornada: novo.prorrogacao_jornada, intervalo_usufruido: novo.intervalo_usufruido };
const calculos = calcularVerbasCaso(caso);
const blocos = aj.blocos || {};
const dados = montarDadosTemplate({ caso, calculos, attrs: caso, dadosReceita: aj.dadosReceita || [], dadosCep: aj.dadosCep || [], blocos });
Object.assign(dados, blocos);
if (blocos.BLOCO_DANO_MORAL) dados.DANO_MORAL_FATO_ESPECIFICO = blocos.BLOCO_DANO_MORAL;
const buf = await (await fetch(url)).arrayBuffer();
const blob = preencherDocxTemplate(buf, dados, { permitirPendencias: true });
fs.writeFileSync(out, Buffer.from(await blob.arrayBuffer()));
console.log(JSON.stringify({ adm: caso.data_admissao, freq: caso.jornada_freq_extra, prorrog: caso.prorrogacao_jornada, iv: caso.intervalo_usufruido, he: calculos.find(c => /prorroga/i.test(c.item)), multas: dados.VALOR_MULTAS_CONV, causa: dados.VALOR_CAUSA_TOTAL }, null, 1));
